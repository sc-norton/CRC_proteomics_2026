symbols <- AnnotationDbi::mapIds(
  org.Hs.eg.db,
  keys      = ensembl_ids,
  keytype   = "ENSEMBL",
  column    = "SYMBOL",
  multiVals = "first"
)

result <- tibble(ensembl_id = ensembl_ids, gene_symbol = unname(symbols[ensembl_ids]))

n_unmapped <- sum(is.na(result$gene_symbol))
if (n_unmapped > 0) {
  cat(sprintf("%d / %d IDs had no SYMBOL mapping in org.Hs.eg.db:\n", n_unmapped, length(ensembl_ids)))
  print(result %>% filter(is.na(gene_symbol)))
}

print(result, n = Inf)
write.csv(result, "ensembl_to_symbol_mapping.csv", row.names = FALSE)